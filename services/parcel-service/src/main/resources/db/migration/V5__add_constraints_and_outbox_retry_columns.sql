-- Constraints and indexes from docs/conventions.md §3, plus the outbox columns the relay needs
-- for retry with backoff and per-parcel ordering.

-- parcels -------------------------------------------------------------------------------------
ALTER TABLE parcels
    ADD CONSTRAINT chk_parcels_status
        CHECK (status IN ('CREATED', 'PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'FAILED')),
    ADD CONSTRAINT chk_parcels_tracking_no
        CHECK (tracking_no ~ '^SD-[2-9A-HJ-NP-Z]{4}-[2-9A-HJ-NP-Z]{4}$'),
    ADD CONSTRAINT chk_parcels_owner
        CHECK (customer_id IS NOT NULL OR merchant_id IS NOT NULL),
    ADD CONSTRAINT chk_parcels_failure_reason
        CHECK (status <> 'FAILED' OR failure_reason IS NOT NULL),
    ADD CONSTRAINT chk_parcels_fee_amount
        CHECK (fee_amount >= 0);

-- The UNIQUE constraint on tracking_no already provides this index
DROP INDEX idx_parcels_tracking_no;

-- Parcel lists are filtered by customer or status and sorted newest first
DROP INDEX idx_parcels_customer;
DROP INDEX idx_parcels_status;
CREATE INDEX idx_parcels_customer_created ON parcels (customer_id, created_at DESC);
CREATE INDEX idx_parcels_status_created   ON parcels (status, created_at DESC);
CREATE INDEX idx_parcels_created          ON parcels (created_at DESC);

-- parcel_status_history -----------------------------------------------------------------------
ALTER TABLE parcel_status_history
    ADD CONSTRAINT chk_status_history_status
        CHECK (status IN ('CREATED', 'PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'FAILED')),
    ADD COLUMN updated_at TIMESTAMPTZ;

-- outbox_events -------------------------------------------------------------------------------
ALTER TABLE outbox_events
    ADD COLUMN aggregate_id    UUID,
    ADD COLUMN seq             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN last_error      VARCHAR(500),
    ADD COLUMN updated_at      TIMESTAMPTZ;

-- Existing rows: the parcel comes from the stored event, and seq follows creation order
UPDATE outbox_events SET aggregate_id = (payload::jsonb ->> 'parcelId')::uuid;

UPDATE outbox_events o
SET seq = ordered.rn
FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM outbox_events) ordered
WHERE o.id = ordered.id;

SELECT setval(pg_get_serial_sequence('outbox_events', 'seq'), COALESCE(MAX(seq), 0) + 1, false)
FROM outbox_events;

-- Retry-state backfill. The relay publishes a parcel's events in seq order and only an earlier
-- PENDING event holds back later ones, so existing rows are sorted out first:
--  1. An unsent event (PENDING or FAILED) older than an event of the same parcel that was already
--     SENT would now arrive after it and roll the status back for consumers. It is PARKED instead:
--     never published, and it does not hold back later events. Rows the previous relay marked SENT
--     were never broker-confirmed; they are treated as delivered.
--  2. The remaining FAILED events were given up on by the previous relay after 10 attempts; they
--     are retried, still in seq order behind any earlier pending event of the same parcel.
UPDATE outbox_events o
SET status     = 'PARKED',
    last_error = 'Superseded before V5: a later event of this parcel was already sent'
WHERE o.status IN ('PENDING', 'FAILED')
  AND EXISTS (SELECT 1
              FROM outbox_events later
              WHERE later.aggregate_id = o.aggregate_id
                AND later.status = 'SENT'
                AND later.seq > o.seq);

UPDATE outbox_events SET status = 'PENDING', next_attempt_at = now() WHERE status = 'FAILED';

ALTER TABLE outbox_events
    ALTER COLUMN aggregate_id SET NOT NULL,
    ADD CONSTRAINT uq_outbox_events_seq UNIQUE (seq),
    ADD CONSTRAINT chk_outbox_events_status CHECK (status IN ('PENDING', 'SENT', 'PARKED'));

DROP INDEX idx_outbox_status_created;
CREATE INDEX idx_outbox_events_due ON outbox_events (next_attempt_at) WHERE status = 'PENDING';
CREATE INDEX idx_outbox_events_aggregate_seq ON outbox_events (aggregate_id, seq);

-- processed_events ----------------------------------------------------------------------------
ALTER TABLE processed_events
    ADD COLUMN updated_at TIMESTAMPTZ;
